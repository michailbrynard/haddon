"""The published inventory is derived from the product, not remembered about it (issue 0008 section D).

``docs/architecture.md`` carries a table of routes, schema objects, migrations and modules.  The hand-written
counts that preceded it drifted and were deleted, so this one is generated by :mod:`haddon.inventory` and
checked here.  Being a test rather than a separate CI step is the point: ``make test-gate`` already runs it, so
the document cannot go stale between one commit and the next.

The first test is the gate.  The rest are about the generator itself, because a check that passed by measuring
nothing would be worse than no check: it would make a stale document look verified.
"""

from __future__ import annotations

import pytest

from haddon import inventory


def test_the_documents_inventory_matches_what_the_product_says():
    """The gate.  When this fails, run ``make inventory`` -- the numbers moved because the product did."""
    assert inventory.check() == []


def test_the_inventory_counts_the_things_it_claims_to_count():
    """Every row is a real measurement of a named thing, so the table cannot pass by being empty or constant."""
    rows = {r.thing: r.count for r in inventory.take()}
    assert len(rows) == len(inventory.take())  # no duplicate row names
    assert all(count > 0 for count in rows.values()), rows
    assert rows["User tables in the migrated schema"] == 23
    assert rows["Triggers"] == 65
    assert rows["Alembic revisions"] == 1


def test_switching_the_extension_off_shrinks_the_published_surface():
    """The row that would be a lie if the switch did nothing: the core-only surface must be strictly smaller."""
    rows = {r.thing: r.count for r in inventory.take()}
    everything = (rows["Entity reads (`GET` under `/v1/entities/{entity_id}`)"]
                  + rows["Entity writes, each a named command"])
    assert 0 < rows["The same surface with the reconciliation extension off"] < everything


def test_a_stale_document_is_reported_rather_than_passed():
    """The mutation probe: change one number in the rendered section and the check has to notice.

    It runs against the rendered text rather than the file, so the check cannot be satisfied by a generator
    that renders whatever the document already says.
    """
    section = inventory.render(inventory.take())
    assert "| Triggers | 65 |" in section
    tampered = section.replace("| Triggers | 65 |", "| Triggers | 64 |")
    current = inventory.DOC.read_text(encoding="utf-8")
    assert inventory.splice(current, tampered) != current


def test_a_document_without_the_markers_is_an_error_not_an_append():
    with pytest.raises(RuntimeError, match="markers"):
        inventory.splice("# a document with no markers\n", inventory.render(inventory.take()))
