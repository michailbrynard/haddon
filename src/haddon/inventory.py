"""Measure the routes, schema objects, migrations and modules that docs/architecture.md counts (issue 0008 section D).

Hand-written counts drift.  A number nobody can re-derive is worse than no number, because it is read as a
measurement.  So the counts that describe the current product are taken from the things themselves:

* routes and commands from the app's mounted routers (:mod:`haddon.api.surface`), with the reconciliation
  extension on and off, so the switch's effect on the published surface is measured rather than asserted;
* tables, views, indexes and triggers from the ``sqlite_master`` of a database built by the real migration;
* migrations from ``db/migrations/``;
* modules from ``src/haddon``.

The result is written into ``docs/architecture.md`` between the markers below.
``tests/test_inventory_is_generated.py`` fails when the file and the source of truth disagree, so the inventory
is part of the commit gate rather than a chore.

The suite's own test count is deliberately left out.  Section D names "routes, schemas, tables and triggers".
Collecting the suite from inside the suite to check a number about the suite is a recursion with no payoff, and
that number changes on every commit anyway.

Usage::

    bin/haddon-inventory            # print the table
    bin/haddon-inventory --write    # rewrite the section in docs/architecture.md
    bin/haddon-inventory --check    # exit non-zero if that section is stale
"""

from __future__ import annotations

import argparse
import sqlite3
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

BEGIN = "<!-- inventory:begin -- generated by bin/haddon-inventory; do not edit by hand -->"
END = "<!-- inventory:end -->"

# ``joinpath`` rather than ``/`` throughout: ``tests/test_no_float_reaches_db.py`` reads every division in
# ``src/`` as a float risk, and a path separator is not worth an allowlist entry that would dull that check.

#: The repository root, when the package is used from a checkout.  ``--write`` and ``--check`` need it; nothing
#: else in the package does, and an installed copy without a checkout simply cannot run them.
ROOT = Path(__file__).resolve().parents[2]
DOC = ROOT.joinpath("docs", "architecture.md")


@dataclass(frozen=True)
class Row:
    """One counted thing, and the sentence that says where the count comes from."""

    thing: str
    count: int
    source: str


def _schema_counts() -> dict[str, int]:
    """Count the schema objects of a database built by the real migration, by ``sqlite_master`` type."""
    from haddon.db.migrate import upgrade

    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp).joinpath("inventory.db")
        upgrade(path)
        con = sqlite3.connect(path)
        try:
            objects = con.execute("SELECT type, name FROM sqlite_master").fetchall()
        finally:
            con.close()
    user = [(kind, name) for kind, name in objects
            if not name.startswith("sqlite_") and name != "alembic_version"]
    return {kind: sum(1 for k, _ in user if k == kind) for kind in ("table", "view", "index", "trigger")}


def _surface() -> dict[str, int]:
    """Count the published entity surface with every extension on, and with reconciliation off."""
    from haddon import extensions
    from haddon.api.app import create_app
    from haddon.api.config import ApiConfig
    from haddon.api.surface import published, service_published

    def counts() -> tuple[int, int]:
        reads, writes = published(create_app(ApiConfig(entities={})))
        return len(reads), len(writes)

    reads, writes = counts()
    with extensions.without(extensions.RECONCILIATION):
        core_reads, core_writes = counts()
    # Routes not relative to an entity (the entity collection) are counted separately, because
    # ``published`` cannot see them and a new one would otherwise move no number here at all.
    service_reads, service_writes = service_published(create_app(ApiConfig(entities={})))
    return {"reads": reads, "writes": writes, "core_reads": core_reads, "core_writes": core_writes,
            "service": len(service_reads) + len(service_writes)}


def _module_counts() -> dict[str, int]:
    pkg = ROOT.joinpath("src", "haddon")
    return {
        "modules": sum(1 for p in pkg.rglob("*.py")),
        "repository": sum(1 for p in pkg.joinpath("repository").glob("*.py") if p.name != "__init__.py"),
        "revisions": sum(1 for p in pkg.joinpath("db", "migrations", "versions").glob("*.py")),
        "migration_files": sum(1 for p in pkg.joinpath("db", "migrations").rglob("*")
                               if p.is_file() and "__pycache__" not in p.parts),
    }


def take() -> list[Row]:
    """Measure every counted thing now."""
    schema = _schema_counts()
    api = _surface()
    code = _module_counts()
    return [
        Row("Entity reads (`GET` under `/v1/entities/{entity_id}`)", api["reads"],
            "`api.surface.published`, every extension on"),
        Row("Entity writes, each a named command", api["writes"],
            "`api.surface.published`, every extension on"),
        Row("Service-level `/v1` routes (not relative to an entity)", api["service"],
            "`api.surface.service_published`: the entity collection"),
        Row("The same surface with the reconciliation extension off", api["core_reads"] + api["core_writes"],
            f"the same app under `HADDON_RECONCILIATION=off`: {api['core_reads']} reads, "
            f"{api['core_writes']} writes"),
        Row("User tables in the migrated schema", schema["table"], "`sqlite_master` of a migrated database"),
        Row("Views", schema["view"], "the same"),
        Row("Indexes", schema["index"], "the same"),
        Row("Triggers", schema["trigger"], "the same"),
        Row("Alembic revisions", code["revisions"], "`db/migrations/versions/`"),
        Row("Files under `db/migrations/`", code["migration_files"], "the same directory, recursively"),
        Row("Python modules under `src/haddon`", code["modules"], "`*.py`, recursively"),
        Row("Repository modules (excluding `__init__`)", code["repository"], "`repository/*.py`"),
    ]


def render(rows: list[Row]) -> str:
    """Render the markdown section, markers included, exactly as it belongs in the document."""
    lines = [BEGIN, "", "| Thing | Count | Taken from |", "|---|---|---|"]
    lines += [f"| {r.thing} | {r.count} | {r.source} |" for r in rows]
    lines += ["", END]
    return "\n".join(lines)


def splice(text: str, section: str) -> str:
    """Replace the marked section of ``text``.

    A document with no markers is an error, not an append.  The section has a place in the argument, and putting
    it somewhere else would be a silent relocation.
    """
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < 0 or end < start:
        raise RuntimeError(f"{DOC} does not carry the {BEGIN!r} / {END!r} markers")
    return text[:start] + section + text[end + len(END):]


def check() -> list[str]:
    """List what is stale; empty when the document already says what the source of truth says."""
    current = DOC.read_text(encoding="utf-8")
    wanted = splice(current, render(take()))
    if current == wanted:
        return []
    have = current[current.find(BEGIN):current.find(END) + len(END)].splitlines()
    want = wanted[wanted.find(BEGIN):wanted.find(END) + len(END)].splitlines()
    problems = [f"docs/architecture.md's generated inventory is stale; run `make inventory`"]
    problems += [f"  -{line}" for line in have if line not in want]
    problems += [f"  +{line}" for line in want if line not in have]
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true", help="rewrite the section in docs/architecture.md")
    group.add_argument("--check", action="store_true", help="exit non-zero if that section is stale")
    args = parser.parse_args(argv)
    if args.check:
        problems = check()
        print("\n".join(problems) if problems else "docs/architecture.md's inventory is current")
        return 1 if problems else 0
    section = render(take())
    if args.write:
        DOC.write_text(splice(DOC.read_text(encoding="utf-8"), section), encoding="utf-8")
        print(f"wrote {DOC.relative_to(ROOT)}")
        return 0
    print(section)
    return 0


if __name__ == "__main__":
    sys.exit(main())
